"""Committed card-enrichment layer.

Source cards are regenerated by ``--build`` and (since the authored overlays
were removed and git-ignored) ship with empty ``connection`` / ``safety`` /
``provenance`` / ``entity_descriptions`` sections — only structural fields and,
for CAPEC, ``allowed_edge_patterns`` / ``relationship_natures`` are populated.

The planner needs authored routing and safety metadata it can trust, so it
carries that metadata here, in version control, and layers it onto the
generated cards at load time. This intentionally replaces the overlay
mechanism for planner purposes without reintroducing git-ignored files.

Merge rule: any non-empty section already present on the generated card wins
(so if overlays ever return, they take precedence); otherwise the authored
defaults below fill the gap. For ``safety`` the per-backend defaults are the
base and the generated card's keys (e.g. CAPEC ``allowed_edge_patterns``) are
layered on top.
"""

