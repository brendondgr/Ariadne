def default_safety_for_backend(backend: str) -> dict[str, Any]:
    """Return the base safety defaults for a runtime backend."""
    if backend == "neo4j":
        return deepcopy(_NEO4J_SAFETY)
    if backend == "gremlin":
        return deepcopy(_GREMLIN_SAFETY)
    return deepcopy(_COMMON_SAFETY)


def enrich(card: dict[str, Any]) -> dict[str, Any]:
    """Return a copy of ``card`` with authored sections filled in.

    A non-empty section already on the card wins; otherwise authored defaults
    are used. ``safety`` is special: the per-backend defaults are the base and
    the generated card's safety keys are layered on top so generated structural
    constraints (``allowed_edge_patterns``) and authored limits both survive.
    """
    merged = deepcopy(card)
    dataset = merged.get("dataset", "")
    backend = merged.get("runtime_backend", "")
    authored = ENRICHMENT.get(dataset, {})

    # safety: backend defaults as base, generated/authored card safety on top.
    base_safety = default_safety_for_backend(backend)
    if dataset in ENRICHMENT:
        base_safety.update(authored.get("safety", {}))
    base_safety.update(merged.get("safety") or {})
    merged["safety"] = base_safety

    # connection / provenance / entity_descriptions: card wins only if non-empty.
    for section in ("connection", "provenance", "entity_descriptions"):
        if not merged.get(section):
            merged[section] = deepcopy(authored.get(section, {}))

    return merged
