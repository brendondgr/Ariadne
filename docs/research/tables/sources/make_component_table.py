#!/usr/bin/env python3
"""Promoted table: tab-component.

    Source experiment: EXP-2026-07-008
    Output:            docs/research/tables/tab-component.{md,tex}

Reads `data/metrics.json`. No number is typed here.

The caption is not decoration. Every 1.0 in this table is a **ceiling by
construction** — the specialists fill validated templates rather than generating
queries — and a table that prints 1.0 without saying so overclaims. The caption
says so in both output formats.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SRC = ROOT / "docs/research/experiments/EXP-2026-07-008-component-evaluation/data/metrics.json"
OUT = ROOT / "docs/research/tables"
STEM = "tab-component"

CAPTION = (
    "Component-level evaluation. Query validity and safety adherence are "
    "ceilings by construction: the specialists fill validated read-only "
    "templates rather than generating queries, so these are design properties, "
    "not tuned results. Deterministic scoring, no LLM judge."
)


def rows(data: dict) -> list[tuple[str, str, str]]:
    a = data["specialists"]["attack"]
    c = data["specialists"]["capec"]
    return [
        ("Query validity (first-pass)", f'{a["query_validity_first_pass"]:.3f} ({a["query_validity_k"]})',
         f'{c["query_validity_first_pass"]:.3f} ({c["query_validity_k"]})'),
        ("Execution accuracy (exact-set-match)", f'{a["execution_exact_set_match"]:.3f} ({a["execution_k"]})',
         f'{c["execution_exact_set_match"]:.3f} ({c["execution_k"]})'),
        ("Precision / recall / F1", f'{a["precision"]} / {a["recall"]} / {a["f1"]}',
         f'{c["precision"]} / {c["recall"]} / {c["f1"]}'),
        ("Safety adherence (audited, breaches)", f'{a["safety_adherence"]:.3f} ({a["audited"]}, {a["breaches"]})',
         f'{c["safety_adherence"]:.3f} ({c["audited"]}, {c["breaches"]})'),
        ("Adversarial block rate (probes, leaks)", f'{a["adversarial_block_rate"]:.3f} ({a["probes"]}, {a["leaks"]})',
         f'{c["adversarial_block_rate"]:.3f} ({c["probes"]}, {c["leaks"]})'),
        ("Latency p50 / p95 / p99 (ms)",
         f'{a["latency_ms"]["p50"]} / {a["latency_ms"]["p95"]} / {a["latency_ms"]["p99"]}',
         f'{c["latency_ms"]["p50"]} / {c["latency_ms"]["p95"]} / {c["latency_ms"]["p99"]}'),
    ]


def planner_rows(data: dict) -> list[tuple[str, str, str, str]]:
    p = data["planner"]
    def cell(key: str, fmt: str = "{:.3f}") -> tuple[str, str, str]:
        d = p[key]
        return (fmt.format(d["overall"]),
                fmt.format(d["dev"]) if "dev" in d else "—",
                fmt.format(d["holdout"]) if "holdout" in d else "—")
    out = []
    for label, key, fmt in (
        ("Source precision", "source_precision", "{:.3f}"),
        ("Source recall", "source_recall", "{:.3f}"),
        ("Sub-question quality", "subquestion_quality", "{:.3f}"),
        ("Routing accuracy", "routing_accuracy", "{:.3f}"),
        ("Schema adherence", "schema_adherence", "{:.3f}"),
        ("Honesty (unsupported/partial)", "honesty", "{:.3f}"),
    ):
        out.append((label, *cell(key, fmt)))
    u = p["unnecessary_source_calls"]
    out.append(("Unnecessary source calls", str(u["overall"]), str(u["dev"]), str(u["holdout"])))
    return out


def as_markdown(data: dict) -> str:
    lines = [
        "<!-- GENERATED by tables/sources/make_component_table.py — DO NOT EDIT.",
        "     Source: EXP-2026-07-008. Regenerate with: make figures -->",
        "",
        "### Planner (deterministic drafter, "
        f'{data["planner"]["corpus"]["cases"]} cases)',
        "",
        "| Metric | Overall | Dev | Holdout |",
        "|---|---|---|---|",
    ]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in planner_rows(data)]
    lines += ["", "### Specialists", "", "| Metric | attack (Cypher/Neo4j) | capec (Gremlin) |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows(data)]
    lines += ["", f"*{CAPTION}*", ""]
    return "\n".join(lines)


def tex_escape(s: str) -> str:
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


def as_latex(data: dict) -> str:
    body = "\n".join(
        f"{tex_escape(a)} & {tex_escape(b)} & {tex_escape(c)} \\\\"
        for a, b, c in rows(data)
    )
    return (
        "% GENERATED by tables/sources/make_component_table.py — DO NOT EDIT.\n"
        "% Source: EXP-2026-07-008. Regenerate with: make figures\n"
        "\\begin{table}[t]\n\\centering\n"
        "\\begin{tabular}{lrr}\n\\toprule\n"
        "Metric & attack (Cypher/Neo4j) & capec (Gremlin) \\\\\n\\midrule\n"
        f"{body}\n"
        "\\bottomrule\n\\end{tabular}\n"
        f"\\caption{{{tex_escape(CAPTION)}}}\n"
        "\\label{tab:component}\n\\end{table}\n"
    )


def main() -> int:
    if not SRC.is_file():
        print(f"error: missing {SRC}", file=sys.stderr)
        return 1
    data = json.loads(SRC.read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{STEM}.md").write_text(as_markdown(data))
    (OUT / f"{STEM}.tex").write_text(as_latex(data))
    print(f"wrote {(OUT / f'{STEM}.md').relative_to(ROOT)}")
    print(f"wrote {(OUT / f'{STEM}.tex').relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
