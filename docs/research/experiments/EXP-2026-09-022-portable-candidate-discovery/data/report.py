"""Regenerate this experiment's prose and tables from recorded metrics only."""
import json
from pathlib import Path

EXP = Path(__file__).resolve().parents[1]
data = json.loads((EXP / "data/metrics.json").read_text())
values = data["values"]


def value(key):
    return values[key]["mean"]


def fmt(key):
    return f"{value(key):.4f}"


table = ["| Tier | Eligible / total | Pooled R@10 | Fields R@10 | Graph R@10 | Fields R@1 | Fields R@20 |",
         "|---|---:|---:|---:|---:|---:|---:|"]
rank_table = ["| Tier | Pooled R@1 | Pooled R@5 | Pooled R@10 | Pooled R@20 |",
              "|---|---:|---:|---:|---:|"]
for tier, info in data["tiers"].items():
    if tier == "T6":
        continue
    keys = [f"{arm}_{tier}_anchor_recall_at_10" for arm in ("pooled", "fields", "graph")]
    keys += [f"fields_{tier}_anchor_recall_at_{k}" for k in (1, 20)]
    table.append(f"| {tier} | {info['eligible']} / {info['n']} | " + " | ".join(map(fmt, keys)) + " |")
    rank_table.append(f"| {tier} | " + " | ".join(fmt(f"pooled_{tier}_anchor_recall_at_{k}") for k in (1, 5, 10, 20)) + " |")
table_text = "\n".join(table)
rank_text = "\n".join(rank_table)
(EXP / "tables/discovery.md").write_text(table_text + "\n")
(EXP / "tables/pooled-budgets.md").write_text(rank_text + "\n")

