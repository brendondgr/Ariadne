"""Generate the README banner from the project logo. Run: python3 scripts/make_header.py

Reads images/logos/Ariadne_LogoONLY.svg and writes images/header.svg. The logo file
stays the only copy of the drawing; this copies its paths in on every run.
The TAGLINE below duplicates the README's opening sentence — change one, re-run this.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGO = ROOT / "images/logos/Ariadne_LogoONLY.svg"
LOGO_W, LOGO_H = 1060.986, 917.0          # its viewBox size (not square)
OUT = ROOT / "images/header.svg"

TITLE = "Ariadne"
TAGLINE = (
    "Live, read-only federated querying across cybersecurity knowledge graphs",
    "that don't share a query language — planned, queried, and cited per engine.",
)
LANGUAGES = [                              # dot colours: GitHub's own language colours
    ("Python", "#3572a5"),
    ("TypeScript", "#3178c6"),
    ("Shell", "#89e051"),
]
STACK = [(n, None) for n in ("LangGraph", "FastAPI", "Neo4j", "Gremlin", "Next.js", "Docker")]

PANEL_BG, PANEL_EDGE = "#0a0c0d", "#1c2123"
CHIP_BG, CHIP_EDGE = "#101415", "#2a3033"
TEXT, CHIP_TEXT, MUTED = "#e9e6df", "#c9ccc7", "#8e948f"
DISC = None                                # logo is teal/gold: it reads on the dark panel

SANS = "ui-sans-serif,-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif"
MONO = "ui-monospace,SFMono-Regular,Menlo,Consolas,'DejaVu Sans Mono',monospace"

W = 1000
MARK, MARK_CY = 148.0, 122.0               # logo height, and its centre from the top
TITLE_Y, TITLE_SIZE = 264, 66
TAGLINE_Y, TAGLINE_SIZE, LINE_H = 302, 19, 28
ROWS_Y, ROW_H = 372, 46
CHIP_H, CHIP_FS, CHIP_GAP, CHIP_PAD = 32, 14.0, 10.0, 15.0
DOT_R, DOT_GUTTER, ADVANCE = 4.0, 13.0, 0.6

rows = [r for r in (LANGUAGES, STACK) if r]
H = int(ROWS_Y + ROW_H * (len(rows) - 1) + CHIP_H + 24)


def logo_paths():
    raw = re.sub(r"<metadata>.*?</metadata>", "", LOGO.read_text(), flags=re.S)
    return raw[raw.index(">", raw.index("<svg")) + 1 : raw.rindex("</svg>")].strip()


def chip_row(items, y):
    widths = [
        CHIP_PAD * 2 + len(label) * CHIP_FS * ADVANCE + (DOT_GUTTER if dot else 0.0)
        for label, dot in items
    ]
    x = (W - (sum(widths) + CHIP_GAP * (len(items) - 1))) / 2
    parts = []
    for (label, dot), width in zip(items, widths):
        text_x = x + CHIP_PAD
        parts.append(
            f'<rect x="{x:.1f}" y="{y:g}" width="{width:.1f}" height="{CHIP_H}" '
            f'rx="{CHIP_H / 2:g}" fill="{CHIP_BG}" stroke="{CHIP_EDGE}" />'
        )
        if dot:
            parts.append(
                f'<circle cx="{text_x + DOT_R:.1f}" cy="{y + CHIP_H / 2:.1f}" '
                f'r="{DOT_R:g}" fill="{dot}" />'
            )
            text_x += DOT_GUTTER
        parts.append(
            f'<text x="{text_x:.1f}" y="{y + CHIP_H / 2 + 5:.1f}" font-family="{MONO}" '
            f'font-size="{CHIP_FS:g}" fill="{CHIP_TEXT}">{label}</text>'
        )
        x += width + CHIP_GAP
    return "\n  ".join(parts)


cx = W / 2
scale = MARK / LOGO_H
disc = (
    f'<circle cx="{cx:g}" cy="{MARK_CY:g}" r="{MARK * 28 / 24 / 2:.1f}" fill="{DISC}" />'
    if DISC
    else ""
)
taglines = "\n  ".join(
    f'<text x="{cx:g}" y="{TAGLINE_Y + i * LINE_H:g}" text-anchor="middle" '
    f'font-family="{SANS}" font-size="{TAGLINE_SIZE}" fill="{MUTED}">{line}</text>'
    for i, line in enumerate(TAGLINE)
)
chips = "\n  ".join(chip_row(row, ROWS_Y + i * ROW_H) for i, row in enumerate(rows))

OUT.write_text(f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" \
width="{W}" height="{H}" role="img" aria-label="{TITLE}">
  <!-- Generated by scripts/make_header.py - edit that, not this. -->
  <rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="24" fill="{PANEL_BG}" \
stroke="{PANEL_EDGE}" />
  {disc}
  <g transform="translate({cx - LOGO_W * scale / 2:.1f},{MARK_CY - MARK / 2:.1f}) \
scale({scale:.6f})">
    {logo_paths()}
  </g>
  <text x="{cx:g}" y="{TITLE_Y}" text-anchor="middle" font-family="{SANS}" \
font-size="{TITLE_SIZE}" font-weight="700" letter-spacing="-1" fill="{TEXT}">{TITLE}</text>
  {taglines}
  {chips}
</svg>
""")
print(f"wrote {OUT.relative_to(ROOT)}")
