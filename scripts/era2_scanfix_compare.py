"""EXP-2026-11-016: this run against EXP-2026-11-015, paired on the same items.

    uv run python scripts/era2_scanfix_compare.py

Reported, not gated (PROTOCOL "Reported"):

* each arm of this run minus the same arm of EXP-2026-11-015: ``records_exact`` per tier,
  the confidently-wrong count over T0-T5, and the dev ``lost`` / ``confidently_wrong`` counts.
  The bootstrap is the EXP-2026-11-015 scorer's (2,000 resamples, seed 20261118; variants
  clustered by gold question). E against E is the run-to-run noise floor.
* the scan guard: questions whose plan had a scan refused, how many the repair turn then fixed,
  and how many legitimate scans it blocked (a refusal that stayed on a question whose reference
  capture is a scan template).

Writes ``<new data>/compare.json`` and ``<new exp>/tables/compare.md``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts import era2_catalog_score as S  # noqa: E402

REPO = S.REPO
OLD_RUNS = REPO / "docs/evaluation/experiments/tool-catalog-2026-11-18"
NEW_RUNS = REPO / "docs/evaluation/experiments/scan-fix-2026-11-19"
NEW_DATA = REPO / "docs/research/experiments/EXP-2026-11-016-era2-scan-fix/data"
SCAN_REFUSAL = "a scan lists every"


def _logs(row_or_artifact: dict[str, Any], dev: bool) -> list[dict[str, Any]]:
    logs = (row_or_artifact.get("run_meta") or {}).get("typed") if dev else row_or_artifact.get("typed")
    if isinstance(logs, dict):
        return [logs]
    return [x for x in logs or [] if isinstance(x, dict)]


def scan_guard(items: list[dict[str, Any]], dev: bool, scan_cases: set[str] | None = None) -> dict[str, int]:
    """Questions where the guard refused a scan, and what happened after."""
    hit = fixed = still = blocked_legit = 0
    for it in items:
        refusals = [r for lg in _logs(it, dev) for r in lg.get("refusals") or []
                    if SCAN_REFUSAL in str(r.get("detail") or "")]
        if not refusals:
            continue
        hit += 1
        final = any(r.get("final") for r in refusals)
        if final:
            still += 1
            if scan_cases is not None and str(it.get("case_id")) in scan_cases:
                blocked_legit += 1
        else:
            fixed += 1
    out = {"questions_with_a_scan_refused": hit, "fixed_by_repair": fixed, "still_refused": still}
    if scan_cases is not None:
        out["legitimate_scans_blocked"] = blocked_legit
    return out


def compare(old_runs: Path, new_runs: Path, authored_dir: Path) -> dict[str, Any]:
    authored = S.load_dev(authored_dir)
    out: dict[str, Any] = {"variants": {}, "dev": {}, "scan_guard": {}}
    ref = json.loads((new_runs / "variants" / "reference.json").read_text())
    scan_cases = {str(r["case_id"]) for r in ref if "scan" in str(r.get("expected_template") or "")}
    for arm in ("E", "T-lazy", "T-full", "T-lazy-G"):
        o, n = old_runs / "variants" / f"{arm}.json", new_runs / "variants" / f"{arm}.json"
        if o.exists() and n.exists():
            old, new = S.load_variant_rows(o), S.load_variant_rows(n)
            tiers = sorted({str(r.get("tier")) for r in new})
            out["variants"][arm] = {
                "records_exact_by_tier": {t: S.paired_variants(new, old, lambda r: float(bool(r["records_exact"])),
                                                               (t,)) for t in tiers},
                "confidently_wrong_T0_T5": S.paired_variants(new, old,
                                                             lambda r: float(S.confidently_wrong_variant(r)),
                                                             S.CW_TIERS, stat="sum")}
            out["scan_guard"].setdefault(arm, {})["variants"] = scan_guard(new, False, scan_cases)
        sub = S.DEV_ARMS[arm]
        od, nd = old_runs / sub / "answers", new_runs / sub / "answers"
        if od.is_dir() and nd.is_dir():
            old_d, new_d = S.load_dev(od), S.load_dev(nd)
            out["dev"][arm] = {k: S.paired_dev(new_d, old_d, authored, k) for k in ("lost", "confidently_wrong")}
            out["scan_guard"].setdefault(arm, {})["dev"] = scan_guard(list(new_d.values()), True)
    return out


def table(c: dict[str, Any]) -> str:
    lines = ["# EXP-2026-11-016 against EXP-2026-11-015 (paired, same items)", "",
             "Generated by `scripts/era2_scanfix_compare.py`. Do not edit by hand. Each cell is this run "
             "minus EXP-2026-11-015 for the same arm, with a 95% bootstrap interval "
             "(2,000 resamples, seed 20261118). E against E is the run-to-run noise floor.", "",
             "| Arm | T0 | T1 | T4 | T5 | CW T0–T5 (count) | dev lost (count) | dev CW (count) |",
             "|---|---|---|---|---|---|---|---|"]
    for arm in ("E", "T-lazy", "T-full", "T-lazy-G"):
        v, d = c["variants"].get(arm) or {}, c["dev"].get(arm) or {}
        rt = v.get("records_exact_by_tier") or {}
        lines.append(f"| {arm} | {S._ci(rt.get('T0'))} | {S._ci(rt.get('T1'))} | {S._ci(rt.get('T4'))} | "
                     f"{S._ci(rt.get('T5'))} | {S._ci(v.get('confidently_wrong_T0_T5'))} | "
                     f"{S._ci(d.get('lost'))} | {S._ci(d.get('confidently_wrong'))} |")
    lines += ["", "## The scan guard", "",
              "| Arm | set | questions with a scan refused | fixed by repair | still refused | "
              "legitimate scans blocked |", "|---|---|---|---|---|---|"]
    for arm, g in c["scan_guard"].items():
        for where in ("variants", "dev"):
            x = g.get(where)
            if x:
                lines.append(f"| {arm} | {where} | {x['questions_with_a_scan_refused']} | {x['fixed_by_repair']} | "
                             f"{x['still_refused']} | {x.get('legitimate_scans_blocked', '—')} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--old-runs", default=str(OLD_RUNS))
    ap.add_argument("--new-runs", default=str(NEW_RUNS))
    ap.add_argument("--data", default=str(NEW_DATA))
    ap.add_argument("--authored", default=str(S.AUTHORED))
    args = ap.parse_args(argv)
    c = compare(Path(args.old_runs), Path(args.new_runs), Path(args.authored))
    data = Path(args.data)
    (data / "compare.json").write_text(json.dumps(c, indent=2, sort_keys=True) + "\n")
    tables = data.parent / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "compare.md").write_text(table(c))
    print(table(c))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
